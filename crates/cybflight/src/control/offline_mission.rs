//! Offline-prebaked mission trajectory.
//!
//! Verbatim copy of `tmp/planning_results/trajectory_slow.yaml`: a
//! 60-piece schedule whose per-piece durations were solved offline by
//! a heavier planner. The mission_planner task feeds these waypoints
//! + segment durations directly into a [`MincoSnap`] solver,
//! bypassing the on-device BFGS optimizer.
//!
//! `OFFLINE_TIMESTAMPS[i]` is the absolute time of arrival at
//! `OFFLINE_WAYPOINTS[i]` measured from the trajectory start. Segment
//! durations are recovered by consecutive differences, with the first
//! segment running from `t=0` to `OFFLINE_TIMESTAMPS[0]`.
//!
//! ## MINCO contract (n = `OFFLINE_NUM_PIECES`)
//!
//! For an `n`-piece trajectory, `MincoSnap` consumes `n−1` intermediate
//! waypoints plus a tail. The YAML provides `n` waypoints — `wp[0..n−1]`
//! are the intermediates and `wp[n−1]` is the tail. The offline schedule
//! maps 1:1 onto the solver, no degenerate hover at the end.
//!
//! [`MincoSnap`]: cybflight_core::trajectory_planning::minco_snap::MincoSnap

#![cfg(feature = "outer_mpc")]

/// Number of polynomial pieces in the offline trajectory. Equal to
/// the YAML's waypoint count and timestamp count (the MINCO solver
/// uses `n−1` of the waypoints as intermediates and the last as the
/// tail boundary).
pub const OFFLINE_NUM_PIECES: usize = 60;

